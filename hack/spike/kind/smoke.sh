# Spike S1: create one sandbox on the kind cluster from up.sh, run
# `exec --no-tty -- echo ok`, and check a stdin round-trip through `cat`.
#
# Needs the OpenShell CLI 0.1.7 as $OPENSHELL (or on PATH). CLI state goes to a
# temporary XDG_CONFIG_HOME, never to the user's own config.

# Needs bash 5 (ADR 0090); keep this line above any bash 4+ syntax.
[ "${BASH_VERSINFO:-0}" -ge 5 ] || { echo "Koinon's scripts need bash 5 or newer (this is $BASH_VERSION); on macOS: brew install bash" >&2; exit 2; }

set -euo pipefail

CLUSTER=${CLUSTER:-koinon-s1}
CTX="kind-${CLUSTER}"
PORT=${PORT:-18081}
IMAGE=${IMAGE:-docker.io/library/busybox:1.37.0}
NAME=${NAME:-s1}
OPENSHELL=${OPENSHELL:-openshell}
K=(kubectl --context "$CTX")

work=$(mktemp -d "${TMPDIR:-/tmp}/smoke.XXXXXX")
export XDG_CONFIG_HOME="$work/config"
pf_pid=
cleanup() { [[ -n "$pf_pid" ]] && kill "$pf_pid" 2>/dev/null; rm -rf "$work"; }
trap cleanup EXIT

fail() { echo "SMOKE FAIL: $*" >&2; exit 1; }
step() { echo "== $(date -u +%H:%M:%SZ) $*"; ts=$(date +%s); }
done_step() { echo "-- $1: $(( $(date +%s) - ts ))s"; }

# mTLS client bundle generated by the chart's certgen hook.
mtls="$XDG_CONFIG_HOME/openshell/gateways/kind/mtls"
mkdir -p "$mtls"
for k in ca.crt tls.crt tls.key; do
  "${K[@]}" -n openshell get secret openshell-client-tls -o "jsonpath={.data.${k//./\\.}}" \
    | base64 -d > "$mtls/$k"
done
chmod 600 "$mtls/tls.key"

"${K[@]}" -n openshell port-forward svc/openshell "${PORT}:8080" >"$work/pf.log" 2>&1 &
pf_pid=$!
for _ in $(seq 30); do nc -z 127.0.0.1 "$PORT" 2>/dev/null && break; sleep 1; done

"$OPENSHELL" gateway add "https://127.0.0.1:${PORT}" --local --name kind
"$OPENSHELL" gateway select kind
export OPENSHELL_GATEWAY=kind

step "sandbox create $NAME ($IMAGE)"
"$OPENSHELL" sandbox create --name "$NAME" --from "$IMAGE" --detach --no-tty \
  --no-auto-providers -- /bin/sleep 3600
# Capture first: `get | grep -q` under pipefail can fail on SIGPIPE.
for _ in $(seq 120); do
  info=$("$OPENSHELL" sandbox get "$NAME" 2>/dev/null || true)
  [[ "$info" == *"Phase: Ready"* ]] && break
  sleep 1
done
echo "$info" | sed -n '1,/Policy:/p'
[[ "$info" == *"Phase: Ready"* ]] || fail "sandbox $NAME not Ready"
done_step create

step "exec echo ok"
out=$("$OPENSHELL" sandbox exec --name "$NAME" --no-tty -- echo ok)
echo "$out"
[[ "$out" == ok ]] || fail "exec printed '$out'"
done_step exec

step "exec stdin round-trip"
line="koinon-s1-$(date +%s)"
back=$(printf '%s\n' "$line" | "$OPENSHELL" sandbox exec --name "$NAME" --no-tty -- cat)
echo "$back"
[[ "$back" == "$line" ]] || fail "stdin round-trip returned '$back'"
done_step stdin

step "NetworkPolicy enforced on workload pods"
# A plain pod with the workload label must get no egress (OpenShell's
# openshell-sandbox-workloads policy); an unlabelled control pod must.
ns=$("${K[@]}" get sandbox -A --field-selector "metadata.name=$NAME" -o custom-columns=NS:.metadata.namespace --no-headers)
# kube-network-policies picks up a new pod IP a second or two after the pod is
# Ready and fails open until then, so poll for up to 30 s.
probe() { # name labels want
  local r=
  "${K[@]}" -n "$ns" run "$1" --image="$IMAGE" --restart=Never --labels="$2" \
    --command -- /bin/sleep 300 >/dev/null
  "${K[@]}" -n "$ns" wait --for=condition=Ready "pod/$1" --timeout=60s >/dev/null
  local t
  t=$(date +%s)
  for _ in $(seq 30); do
    r=$("${K[@]}" -n "$ns" exec "$1" -- /bin/sh -c 'nc -z -w 1 10.96.0.1 443 && echo open || echo blocked')
    [[ "$r" == "$3" ]] && break
    sleep 1
  done
  "${K[@]}" -n "$ns" delete pod "$1" --now >/dev/null
  echo "$r after $(( $(date +%s) - t ))s"
}
control=$(probe np-control koinon.dev/probe=control open)
workload=$(probe np-workload openshell.ai/boundary-role=workload blocked)
echo "control: $control; workload: $workload"
[[ "$control" == open* && "$workload" == blocked* ]] || fail "NetworkPolicy not enforced"
done_step netpol

echo "SMOKE PASS"
