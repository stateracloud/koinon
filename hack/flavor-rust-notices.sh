#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Generates harnesses/opencode/doc/THIRD_PARTY_NOTICES.md (#63): the crate dependency notices for
# the Rust tools the OpenCode flavor ships (ripgrep, fd, ast-grep). Each tool's own licence ships
# separately in the image (the Dockerfile's `licenses` and `tools` stages); this covers what each
# tool's Cargo.lock pulls in, with cargo-about (pinned in hack/versions.env), against
# harnesses/opencode/about.toml and about.hbs.
#
# Usage: hack/flavor-rust-notices.sh
#
# What it does, for each (repo, tag) pair below:
#   1. Fetches the tagged source tree (github.com/<repo>/archive/refs/tags/<tag>.tar.gz).
#   2. Runs `cargo about generate --fail -c about.toml -m <crate>/Cargo.toml about.hbs`
#      against the tool's own Cargo.lock (never regenerated: --locked), so the notice matches the
#      exact dependency versions the release binary was built from.
#   3. Concatenates the three outputs into harnesses/opencode/doc/THIRD_PARTY_NOTICES.md with a
#      per-tool header naming the tool and the pinned version (the Dockerfile's build-time check
#      greps for these, so a re-pin that forgets to rerun this script fails the image build).
#
# Needs network access to github.com (source tarballs) and to crates.io's registry and download
# endpoints (cargo-about resolves and reads each dependency's licence from there); it downloads and
# executes the cargo-about binary. Run it on a machine that allows both, commit the result, and
# wire the generated file into the Dockerfile (COPY the checked-in file, as the GPL offer and the
# OpenCode/Bun notices already are) the next time this runs successfully; see harnesses/opencode/README.md,
# "Rust tool dependency notices".
#
# Re-pinning a tool: update its (repo, tag, version) below and in the Dockerfile together, rerun
# this script, and commit the new THIRD_PARTY_NOTICES.md alongside the Dockerfile change.

# Needs bash 5 (ADR 0090); keep this line above any bash 4+ syntax.
[ "${BASH_VERSINFO:-0}" -ge 5 ] || { echo "Koinon's scripts need bash 5 or newer (this is $BASH_VERSION); on macOS: brew install bash" >&2; exit 2; }

set -euo pipefail

cd "$(dirname "$0")/.."
# shellcheck source=versions.env
. hack/versions.env

harness_dir=harnesses/opencode
out=$harness_dir/doc/THIRD_PARTY_NOTICES.md

# repo, tag, the version string the Dockerfile's build-time check expects to find, and the path
# to the crate's Cargo.toml inside the extracted archive (the archive's top directory is
# "<repo-basename>-<tag-without-leading-v>", GitHub's own naming for a tag archive).
tools=(
	"BurntSushi/ripgrep 15.2.0 ripgrep 15.2.0 ."
	"sharkdp/fd v10.5.0 fd 10.5.0 ."
	"ast-grep/ast-grep 0.51.0 ast-grep 0.51.0 crates/cli"
)

work=$(mktemp -d "${TMPDIR:-/tmp}/flavor-rust-notices.XXXXXX")
trap 'rm -rf "$work"' EXIT

arch=amd64
case $(uname -m) in
x86_64) arch=amd64 ;;
aarch64 | arm64) arch=arm64 ;;
*) echo "flavor-rust-notices: unsupported host arch $(uname -m)" >&2; exit 1 ;;
esac
case $arch in
amd64) cargo_about_sha256=$CARGO_ABOUT_SHA256_AMD64 cargo_about_target=x86_64-unknown-linux-musl ;;
arm64) cargo_about_sha256=$CARGO_ABOUT_SHA256_ARM64 cargo_about_target=aarch64-unknown-linux-musl ;;
esac

cargo_about_tgz=$work/cargo-about.tar.gz
hack/fetch-pinned.sh \
	"https://github.com/EmbarkStudios/cargo-about/releases/download/${CARGO_ABOUT_VERSION}/cargo-about-${CARGO_ABOUT_VERSION}-${cargo_about_target}.tar.gz" \
	"$cargo_about_sha256" "$cargo_about_tgz"
tar -xzf "$cargo_about_tgz" -C "$work" --strip-components=1 "cargo-about-${CARGO_ABOUT_VERSION}-${cargo_about_target}/cargo-about"
cargo_about=$work/cargo-about
chmod 0755 "$cargo_about"

: >"$out.tmp"
{
	echo "# Third-party notices, Rust tools (OpenCode flavor)"
	echo
	echo "Generated by hack/flavor-rust-notices.sh with cargo-about ${CARGO_ABOUT_VERSION}."
	echo "Do not hand-edit: rerun the script after re-pinning any of the tools below."
	echo
} >>"$out.tmp"

for entry in "${tools[@]}"; do
	read -r repo tag name version subdir <<<"$entry"
	src=$work/$name
	archive=$work/$name.tar.gz
	# GitHub's tag archive, not a shallow clone: no git needed, and the tarball is content-addressed
	# by the tag, so this stays reproducible for a given (repo, tag).
	curl -fsSL --retry 5 --retry-all-errors -o "$archive" "https://github.com/$repo/archive/refs/tags/$tag.tar.gz"
	mkdir -p "$src"
	tar -xzf "$archive" -C "$src" --strip-components=1
	echo "flavor-rust-notices: generating notices for $name $version ($repo@$tag)"
	{
		echo
		echo "## $name $version"
		echo
	} >>"$out.tmp"
	"$cargo_about" generate --fail --locked \
		-c "$(cd "$harness_dir" && pwd)/about.toml" \
		-m "$src/$subdir/Cargo.toml" \
		"$(cd "$harness_dir" && pwd)/about.hbs" >>"$out.tmp"
done

mkdir -p "$(dirname "$out")"
mv "$out.tmp" "$out"
echo "flavor-rust-notices: wrote $out"
