// Record is one entry of adrs.json: the front matter plus the derived back-links.
type Record struct {
	Number       string   `json:"number"`
	File         string   `json:"file"`
	Title        string   `json:"title"`
	Status       string   `json:"status"`
	Date         string   `json:"date"`
	Area         string   `json:"area"`
	Tags         []string `json:"tags"`
	Decides      string   `json:"decides,omitempty"`
	Amends       []string `json:"amends"`
	AmendedBy    []string `json:"amended_by"`
	Supersedes   []string `json:"supersedes"`
	SupersededBy []string `json:"superseded_by"`
	Relates      []string `json:"relates"`
	RelatedBy    []string `json:"related_by"`
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

func records(adrs []*ADR) []Record {
	d := derive(adrs)
	out := make([]Record, 0, len(adrs))
	for _, a := range adrs {
		m := a.Meta
		out = append(out, Record{
			Number: a.Number, File: a.File, Title: a.Title, Status: m.Status, Date: m.Date, Area: m.Area,
			Tags: nonNil(m.Tags), Decides: m.Decides,
			Amends: nonNil(m.Amends), AmendedBy: nonNil(d.AmendedBy[a.Number]),
			Supersedes: nonNil(m.Supersedes), SupersededBy: nonNil(d.SupersededBy[a.Number]),
			Relates: nonNil(m.Relates), RelatedBy: nonNil(d.RelatedBy[a.Number]),
		})
	}
	return out
}

// outputs are the generated files of docs/adr: name to wanted content.
func outputs(dir string, adrs []*ADR) (map[string][]byte, error) {
	readme, err := os.ReadFile(filepath.Join(dir, "README.md")) //nolint:gosec // dir is the operator argument
	if err != nil {
		return nil, fmt.Errorf("%s/README.md: %w", dir, err)
	}
	head, _, ok := strings.Cut(string(readme), "\n## Index\n")
	if !ok {
		return nil, fmt.Errorf("README.md has no '## Index' heading")
	}
	var idx strings.Builder
	idx.WriteString(head + "\n## Index\n\n| ADR | Title | Status |\n| --- | --- | --- |\n")
	for _, a := range adrs {
		if a.Title == "" || a.Header["Status"] == "" {
			return nil, fmt.Errorf("%s: no '# %s. Title' first line or no '- Status:' line", a.File, a.Number)
		}
		esc := func(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
		pf(&idx, "| [%s](%s) | %s | %s |\n", a.Number, a.File, esc(a.Title), esc(a.Header["Status"]))
	}
	var js bytes.Buffer
	enc := json.NewEncoder(&js)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(records(adrs)); err != nil {
		return nil, err
	}
	g := "# ADR graph\n\n<!-- Generated by hack/adr-index.sh from the ADR front matter. Do not edit. -->\n\n" +
		"Amends (solid arrow, older ADR points to the newer one that changes it) and supersedes (thick arrow).\n" +
		"The `relates` links are left out; `hack/adr graph --relates` draws them.\n\n" +
		"```mermaid\n" + mermaid(adrs, graphOpts{}) + "```\n"
	return map[string][]byte{"README.md": []byte(idx.String()), "adrs.json": js.Bytes(), "graph.md": []byte(g)}, nil
}

type graphOpts struct {
	focus   string // limit to the ADRs within depth of this number
	depth   int
	relates bool
}

// mermaid draws the amends and supersedes links (and, with relates, the relates links).
func mermaid(adrs []*ADR, o graphOpts) string {
	type edge struct{ from, to, kind string }
	var edges []edge
	for _, a := range adrs {
		for _, t := range a.Meta.Amends {
			edges = append(edges, edge{t, a.Number, "amends"})
		}
		for _, t := range a.Meta.Supersedes {
			edges = append(edges, edge{t, a.Number, "supersedes"})
		}
		if o.relates {
			for _, t := range a.Meta.Relates {
				edges = append(edges, edge{a.Number, t, "relates"})
			}
		}
	}
	keep := map[string]bool{}
	if o.focus != "" {
		keep[o.focus] = true
		for range o.depth {
			add := map[string]bool{}
			for _, e := range edges {
				if keep[e.from] || keep[e.to] {
					add[e.from], add[e.to] = true, true
				}
			}
			for n := range add {
				keep[n] = true
			}
		}
	} else {
		for _, e := range edges {
			keep[e.from], keep[e.to] = true, true
		}
	}
	title := map[string]string{}
	for _, a := range adrs {
		title[a.Number] = a.Title
	}
	var nums []string
	for n := range keep {
		nums = append(nums, n)
	}
	sort.Strings(nums)
	var b strings.Builder
	b.WriteString("flowchart LR\n")
	for _, n := range nums {
		t := strings.NewReplacer(`"`, "#quot;", "<", "#lt;", ">", "#gt;").Replace(title[n])
		pf(&b, "  n%s[\"%s: %s\"]\n", n, n, t)
	}
	for _, e := range edges {
		if !keep[e.from] || !keep[e.to] {
			continue
		}
		switch e.kind {
		case "supersedes":
			pf(&b, "  n%s ==>|supersedes| n%s\n", e.from, e.to)
		case "relates":
			pf(&b, "  n%s -.-> n%s\n", e.from, e.to)
		default:
			pf(&b, "  n%s --> n%s\n", e.from, e.to)
		}
	}
	return b.String()
}

// writeOutputs writes the generated files, or with check returns the names that are stale.
func writeOutputs(dir string, adrs []*ADR, check bool) (stale []string, err error) {
	want, err := outputs(dir, adrs)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(want))
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p := filepath.Join(dir, n)
		have, _ := os.ReadFile(p) //nolint:gosec // dir is the operator argument
		if bytes.Equal(have, want[n]) {
			continue
		}
		if check {
			stale = append(stale, n)
			continue
		}
		if err := os.WriteFile(p, want[n], 0o644); err != nil { //nolint:gosec // generated docs are world-readable
			return nil, err
		}
	}
	return stale, nil
}
